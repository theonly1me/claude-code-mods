import { expect, mock, test } from 'claude-code/testing'

test('the scene stays hidden until opened and caps height in both layouts', async ($, on) => {
  mock.clock(on)
  mock.store(on)
  on('ui.render', ($, event) => $.ui.resolve(event).Box({ children: [] }))
  on('session.id', () => ({ value: 'demo' }))
  on('command.register', ($, event) => ({ value: { command: event.name } }))
  on('session.start', ($, event) => ({ cwd: event.cwd }))
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  const props = { hasSurvey: false, isWorking: false, maxRows: 1000, bodyColumns: 120, scroll: { offset: 0, bodyRows: 20 }, view: {} }
  const terminal = await $.ui.mount({ plugin: 'night-feast', surface: 'terminal', component: 'AbovePrompt', props })
  expect((await terminal.findAll({ type: 'Raster' })).length).toBe(0)
  await $.command.run({ command: 'feast', args: 'show', origin: { kind: 'composer' }, presentation: { isFullscreen: false, columns: 120 } })
  const raster = await terminal.find({ type: 'Raster' })
  expect(raster?.props.columns).toBe(120)
  expect(raster?.props.rows).toBe(6)
  await terminal.press({ key: 'size' })
  expect((await terminal.find({ type: 'Raster' }))?.props.rows).toBe(12)
  const desktop = await $.ui.mount({ plugin: 'night-feast', surface: 'desktop', component: 'AbovePrompt', props })
  expect((await desktop.findAll({ type: 'Raster' })).length).toBe(0)
  expect((await desktop.findAll({ type: 'Text' })).length).toBeGreaterThan(0)
  await terminal.press({ key: 'hide' })
  expect((await terminal.findAll({ type: 'Raster' })).length).toBe(0)
})

test('play mode accepts keyboard, pointer, and button actions in a client', async ($, on) => {
  mock.clock(on)
  mock.store(on)
  on('ui.render', ($, event) => $.ui.resolve(event).Box({ children: [] }))
  on('session.id', () => ({ value: 'demo' }))
  on('command.register', ($, event) => ({ value: { command: event.name } }))
  on('session.start', ($, event) => ({ cwd: event.cwd }))
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  await $.command.run({ command: 'feast', args: 'play', origin: { kind: 'composer' }, presentation: { isFullscreen: false, columns: 100 } })
  const ui = await $.ui.mount({ plugin: 'night-feast', surface: 'terminal', component: 'AbovePrompt', props: { hasSurvey: false, isWorking: true, maxRows: 20, bodyColumns: 100, scroll: { offset: 0, bodyRows: 20 }, view: {} }, viewport: { columns: 100, rows: 20, isFullscreen: true } })
  expect((await ui.findAll({ type: 'Text', text: 'Click game' })).length).toBeGreaterThan(0)
  await ui.pointer({ type: 'down', x: 30, y: 3, button: 'left' })
  await ui.key({ key: 'right' })
  await ui.key({ key: ' ' })
  await ui.pointer({ type: 'down', x: 30, y: 5, button: 'left' })
  await ui.advance(160)
  await ui.press({ key: 'jump' })
  expect((await ui.findAll({ type: 'Button', in: 'game' })).length).toBe(3)
})

