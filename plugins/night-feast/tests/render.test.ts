test('reloading an expanded playing scene hides it and restores compact sizing', async ($, on) => {
  mock.clock(on)
  mock.store(on)
  on('ui.render', ($, event) => $.ui.resolve(event).Box({ children: [] }))
  on('session.id', () => ({ value: 'demo' }))
  on('command.register', ($, event) => ({ value: { command: event.name } }))
  on('session.start', ($, event) => ({ cwd: event.cwd }))
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  const command = { command: 'feast', args: 'expanded', origin: { kind: 'composer' }, presentation: { isFullscreen: false, columns: 120 } } as const
  await $.command.run(command)
  await $.command.run({ ...command, args: 'play' })
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  const ui = await $.ui.mount({ plugin: 'night-feast', surface: 'terminal', component: 'AbovePrompt', props: { hasSurvey: false, isWorking: false, maxRows: 1000, bodyColumns: 120, scroll: { offset: 0, bodyRows: 20 }, view: {} } })
  expect((await ui.findAll({ type: 'Raster' })).length).toBe(0)
  expect((await ui.findAll({ type: 'Client' })).length).toBe(0)
  await $.command.run({ ...command, args: 'show' })
  expect((await ui.find({ type: 'Raster' }))?.props.rows).toBe(6)
})
