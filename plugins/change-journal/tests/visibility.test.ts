import { expect, mock, test } from 'claude-code/testing'

test('the view and automatic explanations stay off until explicitly opened', async ($, on) => {
  const clock = mock.clock(on)
  on('session.cwd', () => ({ value: '/demo' }))
  on('command.register', ($, event) => ({ value: { command: event.name } }))
  on('session.start', ($, event) => ({ cwd: event.cwd }))
  on('turn.start', ($, event) => ({ turnId: event.turnId }))
  on('tool.call', () => ({ result: 'Updated' }))
  on('ui.render', ($, event) => $.ui.resolve(event).Box({ children: [] }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('ui.close', () => ({ value: undefined }))
  let calls = 0
  on('model.complete', () => { calls += 1; return { value: { isAnswered: false, reason: 'aborted', usage: { input_tokens: 0, output_tokens: 0, cache_read_input_tokens: 0, cache_creation_input_tokens: 0 } } } })
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  await $.turn.start({ text: 'Edit', turnId: 'one' })
  await $.tool.call({ tool: 'Edit', file_path: '/demo/cart.ts', old_string: 'true', new_string: 'false' })
  const ui = await $.ui.mount({ plugin: 'change-journal', surface: 'terminal', component: 'AbovePrompt', props: { hasSurvey: false, isWorking: false, maxRows: 30, bodyColumns: 100, scroll: { offset: 0, bodyRows: 20 }, view: {} } })
  await clock.advance(3000)
  expect(calls).toBe(0)
  expect((await ui.findAll({ type: 'Button' })).length).toBe(0)
  const command = { command: 'changes', args: 'show', origin: { kind: 'composer' }, presentation: { isFullscreen: false, columns: 100 } } as const
  await $.command.run(command)
  await clock.advance(1000)
  expect(calls).toBe(1)
  expect((await ui.findAll({ type: 'Button' })).length).toBe(1)
  await $.command.run({ ...command, args: 'hide' })
  await $.tool.call({ tool: 'Edit', file_path: '/demo/cart.ts', old_string: 'false', new_string: 'null' })
  await clock.advance(20000)
  expect(calls).toBe(1)
  expect((await ui.findAll({ type: 'Button' })).length).toBe(0)
  await $.command.run(command)
  await $.session.start({ cwd: '/demo', surface: 'terminal', isInteractive: true })
  expect((await ui.findAll({ type: 'Button' })).length).toBe(0)
})
